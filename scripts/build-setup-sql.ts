/**
 * Write supabase/setup.sql: every migration in one file that can be pasted into the
 * Supabase SQL Editor, plus the rows Drizzle uses to remember what has run, so a later
 * `npm run db:migrate` skips them. Use it where a direct database connection is not possible.
 *
 *   npx tsx scripts/build-setup-sql.ts
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8")) as { entries: { tag: string; when: number }[] };
const parts = [
  "-- ARRAE portal: database setup. Generated by scripts/build-setup-sql.ts; do not edit by hand.",
  "BEGIN;",
  'CREATE SCHEMA IF NOT EXISTS "drizzle";',
  'CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
];
for (const { tag, when } of journal.entries) {
  const sql = readFileSync(`drizzle/${tag}.sql`, "utf8");
  const hash = createHash("sha256").update(sql).digest("hex");
  parts.push(`\n-- ${tag}`, sql.split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean).join("\n"));
  parts.push(`INSERT INTO "drizzle"."__drizzle_migrations" (hash, created_at) VALUES ('${hash}', ${when});`);
}
parts.push("COMMIT;", "");
writeFileSync("supabase/setup.sql", parts.join("\n"));
console.log("Wrote supabase/setup.sql");
